"""Write the hematocrit and the albumin over age of NHANES 2013-2018.

The table `pkpdsim/database/tables/blood_nhanes.toml` is generated by this
script from the public files of the examinations 2013-2014, 2015-2016 and
2017-2018 (CDC/NCHS, public domain): demographics (`DEMO`), complete blood
count (`CBC`, the hematocrit `LBXHCT` in %, from 1 year) and standard
biochemistry (`BIOPRO`, the albumin `LBXSAL` in g/dl by bromocresol purple,
from 12 years), all races and Hispanic origins, the women pregnant at the
examination left out, weighted with the 6-year examination weights.

At every age of the grid of each sex: the survey-weighted mean of the
respondents times a Gaussian kernel in age (`BANDWIDTHS`, a choice of the
library: half a year in the growth, five years in the adults, whose kernel
reads the respondents of 18 years and over only), the respondents of 80
years and over (`RIDAGEYR` is top-coded at 80) the last row on their own.
The physiology (`pkpdsim.pbpk.age`) takes the ratio of a value to the value
at 35 years of the same sex, the age of the adult of ICRP 89, so the
hematocrit of the reference individual stays that of ICRP 89.

    uv run python scripts/database/nhanes_blood.py [--cache DIR]
"""

import argparse
import math
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parent))

from nhanes_populations import ROOT, SEXES, TOP_CODED, fetch, fmt

TABLE = ROOT / "src" / "pkpdsim" / "database" / "tables" / "blood_nhanes.toml"
"""The generated table."""

ADULT = 20.0
"""The age (years) from which a row is adult: its kernel reads the respondents
of 18 years and over only."""

BANDWIDTHS: tuple[tuple[float, float], ...] = ((ADULT, 0.5), (math.inf, 5.0))
"""The bandwidth (years) of the Gaussian kernel below an age (years)."""

REFERENCE = 35.0
"""The age (years) of the adult of ICRP 89, a row of every grid."""

QUANTITIES = {
    "hematocrit": ("CBC", "LBXHCT", 0.01, (1.0, *range(2, 20))),
    "albumin": ("BIOPRO", "LBXSAL", 10.0, tuple(range(12, 20))),
}
"""The quantities: the file, the variable, the factor to the unit of the
table (hematocrit fraction, albumin g/l) and the ages of the rows below 20
years (the youngest age the survey measures)."""

ADULT_AGES = (*(float(a) for a in range(20, 80, 5)), REFERENCE, float(TOP_CODED))
"""The ages of the adult rows."""


def bandwidth(age: float) -> float:
    """The bandwidth of the kernel at an age."""
    for upper, h in BANDWIDTHS:
        if age < upper:
            return h
    raise AssertionError(age)


def rows(
    data: pd.DataFrame, column: str, ages: tuple[float, ...]
) -> list[dict[str, float]]:
    """The weighted kernel means of a variable at the ages."""
    out = []
    data = data[data[column].notna()]
    below = data[data["RIDAGEYR"] < TOP_CODED]
    for age in sorted(set(ages)):
        if age == TOP_CODED:
            part = data[data["RIDAGEYR"] == TOP_CODED]
            weights = part["w"].to_numpy()
            n = len(part)
        else:
            h = bandwidth(age)
            part = below[below["RIDAGEYR"] >= ADULT - 2] if age >= ADULT else below
            d = (part["age"].to_numpy() - age) / h
            weights = part["w"].to_numpy() * np.exp(-0.5 * d**2)
            n = int((np.abs(d) <= 2).sum())
        values = part[column].to_numpy()
        out.append(
            {
                "age": age,
                "value": float(weights @ values / weights.sum()),
                "n": n,
                "n_eff": float(weights.sum() ** 2 / (weights**2).sum()),
            }
        )
    return out


def main() -> None:
    """Download the files and write the table."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--cache", type=Path, default=Path.home() / ".cache" / "pkpdsim" / "nhanes"
    )
    args = parser.parse_args()
    lines = [
        "# The hematocrit and the albumin of the residents of the United States over age,",
        "# NHANES 2013-2018, generated by scripts/database/nhanes_blood.py from the public",
        "# files of the survey (DEMO, CBC and BIOPRO of the cycles H, I, J): do not edit.",
        "#",
        "# Survey-weighted kernel means of all races and Hispanic origins, the women",
        "# pregnant at the examination excluded; the row of age 80 are the respondents of",
        "# 80 years and over. Hematocrit as a fraction (LBXHCT / 100), albumin in g/l",
        "# (LBXSAL * 10, bromocresol purple).",
    ]
    for quantity, (stem, column, factor, young) in QUANTITIES.items():
        data = fetch(args.cache, (stem,))
        for sex, code in SEXES.items():
            part = data[data["RIAGENDR"] == code]
            result = rows(part, column, (*young, *ADULT_AGES))
            unit = "dimensionless" if quantity == "hematocrit" else "g/l"
            lines += [
                "",
                f"[{quantity}.{sex}]",
                f'unit = "{unit}"',
                'source = "NHANES2013_2018"',
                f'notes = "survey-weighted kernel means of {column} of the {sex} respondents, '
                'scripts/database/nhanes_blood.py"',
                f"age = [{', '.join(fmt(r['age']) for r in result)}]",
                f"value = [{', '.join(fmt(r['value'] * factor, 5) for r in result)}]",
                f"n = [{', '.join(str(r['n']) for r in result)}]",
                f"n_eff = [{', '.join(str(round(r['n_eff'])) for r in result)}]",
            ]
    TABLE.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {TABLE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
