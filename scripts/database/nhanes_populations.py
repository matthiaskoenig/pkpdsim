"""Write the populations of NHANES 2013-2018 from the public files of the survey.

The populations `white_american_nhanes`, `black_american_nhanes` and
`mexican_american_nhanes` of `pkpdsim/database/tables/populations/` are
generated by this script from the demographics (`DEMO_H`, `DEMO_I`, `DEMO_J`)
and body measures (`BMX_H`, `BMX_I`, `BMX_J`) of the examinations 2013-2014,
2015-2016 and 2017-2018 (public domain, CDC/NCHS):

- the respondents of the race and Hispanic origin (`RIDRETH1`: 3 non-Hispanic
  white, 4 non-Hispanic black, 1 Mexican American) with a body weight and a
  height (the recumbent length below 24 months, the standing height from 24
  months on), without the women pregnant at the examination
  (`RIDEXPRG == 1`), weighted with the 6-year examination weights
  (`WTMEC2YR / 3`);
- the reference individual of each sex: the survey-weighted mean body weight,
  height and age of the adults of 20 to 49 years, the default individual of a
  model built with the population;
- the covariates of each sex over age (`[<sex>.by_age]`): at every age of the
  grid the survey-weighted mean and standard deviation of the height and of
  the logarithm of the body weight and their correlation, the weights of the
  respondents times a Gaussian kernel in age (the age at the examination in
  months below 20 years, in years plus one half above); the bandwidth grows
  with the age (`BANDWIDTHS`, a choice of the library: the growth of an
  infant within months against the slow change of an adult; the kernel of an
  adult row reads the respondents of 18 years and over only); the
  respondents of 80 years and over (`RIDAGEYR` is top-coded at 80) are the
  last row, age 80, on their own; `n` is the number of respondents within two
  bandwidths, `n_eff` the effective number of the kernel weights.

The sampler of virtual individuals (`pkpdsim.pbpk.populations`) draws the
height and the logarithm of the body weight from the bivariate normal
distribution of the age, interpolated linearly between the ages of the grid.

    uv run python scripts/database/nhanes_populations.py [--cache DIR]

downloads the six files into the cache directory (default
`~/.cache/pkpdsim/nhanes`) once and rewrites the three population files.
"""

import argparse
import math
import urllib.request
from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
"""The root of the repository."""

TABLES = ROOT / "src" / "pkpdsim" / "database" / "tables" / "populations"
"""The folder of the population files."""

CYCLES = {"H": 2013, "I": 2015, "J": 2017}
"""The suffixes of the files of the three cycles and the first year of each."""

URL = "https://wwwn.cdc.gov/Nchs/Data/Nhanes/Public/{year}/DataFiles/{name}.xpt"
"""The public files of NHANES."""


AGES: tuple[float, ...] = (
    0.125,
    0.25,
    0.5,
    0.75,
    1.0,
    1.5,
    *(float(a) for a in range(2, 20)),
    *(float(a) for a in range(20, 80, 5)),
    80.0,
)
"""The ages of the rows (years); 80 is the top-coded group of 80 years and over."""

TOP_CODED = 80
"""`RIDAGEYR` of the respondents of 80 years and over."""

MAX_AGE = 100.0
"""The oldest age the population describes: the row of 80 years and over holds
up to it (a choice of the library)."""

ADULT = 20.0
"""The age (years) from which the rows are adults: their kernel reads only the
respondents of 18 years and over, so the wide kernel of the adults does not
reach into the growth."""

BANDWIDTHS: tuple[tuple[float, float], ...] = (
    (1.0, 1.5 / 12),
    (2.0, 3.0 / 12),
    (ADULT, 0.5),
    (math.inf, 2.5),
)
"""The bandwidth (years) of the Gaussian kernel below an age (years)."""


@dataclass(frozen=True)
class Group:
    """A population of the survey."""

    key: str
    name: str
    code: int
    label: str


GROUPS = (
    Group(
        "white_american_nhanes",
        "White American (NHANES 2013-2018)",
        3,
        "non-Hispanic white",
    ),
    Group(
        "black_american_nhanes",
        "Black American (NHANES 2013-2018)",
        4,
        "non-Hispanic black",
    ),
    Group(
        "mexican_american_nhanes",
        "Mexican American (NHANES 2013-2018)",
        1,
        "Mexican American",
    ),
)
"""The populations by `RIDRETH1`."""

SEXES = {"male": 1, "female": 2}
"""The sexes by `RIAGENDR`."""


def fetch(cache: Path, stems: tuple[str, ...]) -> pd.DataFrame:
    """The respondents of the three cycles: demographics merged with the files of `stems`.

    The files are downloaded into `cache` once. The column `age` is the age
    at the examination in years (the months plus one half below 20 years, the
    completed years plus one half above), `w` the 6-year examination weight;
    the women pregnant at the examination are left out.
    """
    cache.mkdir(parents=True, exist_ok=True)
    frames = []
    for suffix, year in CYCLES.items():
        parts = []
        for stem in ("DEMO", *stems):
            name = f"{stem}_{suffix}"
            path = cache / f"{name}.xpt"
            if not path.exists():
                urllib.request.urlretrieve(URL.format(year=year, name=name), path)
            parts.append(pd.DataFrame(pd.read_sas(path, format="xport")))
        frame = parts[0]
        for part in parts[1:]:
            frame = frame.merge(part, on="SEQN")
        frames.append(frame)
    data = pd.concat(frames, ignore_index=True)
    months = data["RIDEXAGM"]
    data["age"] = np.where(
        data["RIDAGEYR"] < 20,
        np.where(months.notna(), (months + 0.5) / 12.0, data["RIDAGEYR"] + 0.5),
        data["RIDAGEYR"] + 0.5,
    )
    data["w"] = data["WTMEC2YR"] / len(CYCLES)
    return data[(data["w"] > 0) & (data["RIDEXPRG"] != 1)]


def download(cache: Path) -> pd.DataFrame:
    """The respondents with a body weight and a height."""
    data = fetch(cache, ("BMX",))
    months = data["RIDEXAGM"]
    infant = months.notna() & (months < 24)
    data = data.assign(
        height=np.where(infant, data["BMXRECUM"], data["BMXHT"]),
        weight=data["BMXWT"],
    )
    return data[data["weight"].notna() & data["height"].notna()]


def bandwidth(age: float) -> float:
    """The bandwidth of the kernel at an age."""
    for upper, h in BANDWIDTHS:
        if age < upper:
            return h
    raise AssertionError(age)


def moments(rows: pd.DataFrame, weights: np.ndarray) -> dict[str, float]:
    """The weighted moments of height and log body weight."""
    w = weights / weights.sum()
    h = rows["height"].to_numpy()
    lw = np.log(rows["weight"].to_numpy())
    mh, ml = float(w @ h), float(w @ lw)
    vh = float(w @ (h - mh) ** 2)
    vl = float(w @ (lw - ml) ** 2)
    cov = float(w @ ((h - mh) * (lw - ml)))
    return {
        "height_mean": mh,
        "height_sd": math.sqrt(vh),
        "ln_bw_mean": ml,
        "ln_bw_sd": math.sqrt(vl),
        "rho": cov / math.sqrt(vh * vl),
        "n_eff": float(weights.sum() ** 2 / (weights**2).sum()),
    }


def by_age(data: pd.DataFrame) -> list[dict[str, float]]:
    """The rows of the covariates over age of one population and sex."""
    rows = []
    below = data[data["RIDAGEYR"] < TOP_CODED]
    for age in AGES:
        if age == TOP_CODED:
            part = data[data["RIDAGEYR"] == TOP_CODED]
            weights = part["w"].to_numpy()
            n = len(part)
        else:
            h = bandwidth(age)
            part = below[below["RIDAGEYR"] >= ADULT - 2] if age >= ADULT else below
            d = (part["age"].to_numpy() - age) / h
            weights = part["w"].to_numpy() * np.exp(-0.5 * d**2)
            n = int((np.abs(d) <= 2).sum())
        row = {"age": age, **moments(part, weights), "n": n}
        rows.append(row)
    return rows


def reference(data: pd.DataFrame) -> dict[str, float]:
    """The survey-weighted means of the adults of 20 to 49 years."""
    part = data[data["RIDAGEYR"].between(20, 49)]
    w = part["w"].to_numpy() / part["w"].sum()
    return {
        "BW": float(w @ part["weight"]),
        "HEIGHT": float(w @ part["height"]),
        "AGE": float(w @ part["age"]),
        "n": len(part),
    }


def fmt(x: float, digits: int = 4) -> str:
    """A number with its significant digits."""
    return repr(float(f"{x:.{digits}g}"))


def write(group: Group, data: pd.DataFrame) -> str:
    """The population file of a group."""
    lines = [
        f"# The {group.label} residents of the United States of the NHANES examinations",
        "# 2013-2018, generated by scripts/database/nhanes_populations.py from the public",
        "# files of the survey (DEMO and BMX of the cycles H, I, J): do not edit.",
        "#",
        "# The reference individual of each sex is the survey-weighted mean of the",
        "# adults of 20 to 49 years (age at examination), the women pregnant at the",
        "# examination excluded; `by_age` are the covariates over age, the",
        "# survey-weighted kernel moments of height and log body weight (see the",
        "# script).",
        "",
        f'name = "{group.name}"',
        'source = "NHANES2013_2018"',
    ]
    for sex, code in SEXES.items():
        part = data[(data["RIDRETH1"] == group.code) & (data["RIAGENDR"] == code)]
        ref = reference(part)
        who = f"{ref['n']} {group.label} {sex} respondents aged 20-49 y"
        lines += [
            "",
            f"[{sex}.reference]",
            f'BW = {{ value = {fmt(ref["BW"])}, unit = "kg", source = "NHANES2013_2018", '
            f'notes = "survey-weighted mean body weight of the {who}" }}',
            f'HEIGHT = {{ value = {fmt(ref["HEIGHT"])}, unit = "cm", source = "NHANES2013_2018", '
            f'notes = "survey-weighted mean height of the {who}" }}',
            f'AGE = {{ value = {fmt(ref["AGE"])}, unit = "yr", source = "NHANES2013_2018", '
            f'notes = "survey-weighted mean age at examination (completed years plus one half) of the {who}" }}',
        ]
        rows = by_age(part)
        lines += [
            "",
            f"[{sex}.by_age]",
            'source = "NHANES2013_2018"',
            f'notes = "survey-weighted kernel moments of the {group.label} {sex} respondents, '
            "scripts/database/nhanes_populations.py; the row of age 80 are the respondents of 80 years and over, "
            'whose distribution the library takes up to 100 years"',
            f"age_range = [0.0, {MAX_AGE!r}]",
        ]
        columns = (
            ("age", 4),
            ("height_mean", 5),
            ("height_sd", 4),
            ("ln_bw_mean", 5),
            ("ln_bw_sd", 4),
            ("rho", 3),
            ("n", 0),
            ("n_eff", 0),
        )
        for col, digits in columns:
            if digits:
                values = ", ".join(fmt(r[col], digits) for r in rows)
            else:
                values = ", ".join(str(round(r[col])) for r in rows)
            lines.append(f"{col} = [{values}]")
    return "\n".join(lines) + "\n"


def main() -> None:
    """Download the files and write the population files."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--cache", type=Path, default=Path.home() / ".cache" / "pkpdsim" / "nhanes"
    )
    args = parser.parse_args()
    data = download(args.cache)
    for group in GROUPS:
        path = TABLES / f"{group.key}.toml"
        path.write_text(write(group, data), encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
