"""Enzymes and transporters, and their inhibition and induction by substances.

The protein table, the declarations of inhibition and induction and the
turnover of the proteins (`turnover`). The SBML is generated by the organs:
the base activity `f_<protein>` of every organ with a process of the protein,
the turnover state `E_<protein>` under mechanism-based inhibition and
induction (`pkpdsim.pbpk.organ_builder`), and the inhibitor terms in the rates
of the processes (`pkpdsim.pbpk.placement`).
"""

from dataclasses import dataclass, replace
from typing import Literal

from pkpdsim.pbpk.data import load, value
from pkpdsim.pbpk.organs import Organ
from pkpdsim.pbpk.units import U
from pkpdsim.pbpk.values import Q, Value

__all__ = [
    "PROTEINS",
    "Induction",
    "Inhibition",
    "Protein",
    "load_proteins",
    "turnover",
]


@dataclass(frozen=True)
class Protein:
    """An enzyme or a transporter, named once with its annotation.

    Attributes:
        sid: the id of the protein, also used in `f_<sid>`, `CYP3A4`.
        name: the name of the protein.
        uniprot: the UniProtKB accession of the human protein.
        ncit: the NCI Thesaurus code, if the thesaurus has a concept.
    """

    sid: str
    name: str
    uniprot: str
    ncit: str | None = None


def load_proteins() -> dict[str, Protein]:
    """Load the protein table `data/proteins.toml`.

    Returns:
        The proteins by their id.
    """
    table = load("proteins")["proteins"]
    return {
        sid: Protein(
            sid=sid,
            name=entry["name"],
            uniprot=entry["uniprot"],
            ncit=entry.get("ncit"),
        )
        for sid, entry in table.items()
    }


PROTEINS: dict[str, Protein] = load_proteins()
"""The proteins of the library by their id."""


@dataclass(frozen=True)
class Inhibition:
    """The inhibition of a protein by a substance, declared on the inhibitor.

    It acts on every process of the protein (`pkpdsim.pbpk.placement`):
    competitive on Km, uncompetitive on Vmax and Km, noncompetitive on Vmax,
    mixed on both (Segel 1975); a mechanism-based inhibition inactivates the
    protein (its turnover state, Mayhew 2000) and binds competitively with
    `Ki = KI` while it does. A substance inhibits a protein once.

    Attributes:
        protein: the id of the inhibited protein (key of `PROTEINS`).
        kind: the type of the inhibition.
        ki: the inhibition constant (of the unbound inhibitor, mM), the
            competitive one of a mixed inhibition, the KI of a mechanism-based
            inhibition.
        kiu: the uncompetitive constant of a mixed inhibition, only there.
        kinact: the maximal inactivation rate (1/min) of a mechanism-based
            inhibition, only there.
    """

    protein: str
    kind: Literal[
        "competitive", "noncompetitive", "uncompetitive", "mixed", "mechanism"
    ]
    ki: Q
    kiu: Q | None = None
    kinact: Q | None = None


@dataclass(frozen=True)
class Induction:
    """The induction of a protein by a substance, declared on the inducer.

    It raises the synthesis of the protein, `kdeg*(1 + Emax*I/(EC50 + I))`
    (Almond 2009), so its amount approaches `1 + Emax*I/(EC50 + I)`.

    Attributes:
        protein: the id of the induced protein (key of `PROTEINS`).
        emax: the maximal increase of the expression (fold change - 1).
        ec50: the concentration of half-maximal induction (unbound, mM).
    """

    protein: str
    emax: Q
    ec50: Q


def turnover(organ: Organ) -> Value:
    """Get the degradation rate constant of the proteins in an organ.

    The values of CYP3A4 (`data/proteins.toml`, `[turnover]`): the liver, the
    small intestine, and the hepatic value for every other organ.

    Args:
        organ: the organ.

    Returns:
        `kdeg` (1/min) with its source; the notes state the value of the
        source (1/h).
    """
    key = organ.value if organ in (Organ.LIVER, Organ.SMALL_INTESTINE) else "other"
    v = value("proteins", "turnover", key)
    return replace(
        v,
        value=v.value / 60.0,
        unit=U.per_min,
        notes=f"{v.value} 1/h: {v.notes}",
    )
