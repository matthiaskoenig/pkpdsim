"""Enzymes and transporters, and their inhibition and induction by substances.

The dataclasses only: the activity factor of a protein, the effect of an
inhibitor and of an inducer on the processes of the protein are generated by
the builder.
"""

from dataclasses import dataclass
from typing import Literal

from pkpdsim.pbpk.data import load
from pkpdsim.pbpk.values import Q

__all__ = ["PROTEINS", "Induction", "Inhibition", "Protein", "load_proteins"]


@dataclass(frozen=True)
class Protein:
    """An enzyme or a transporter, named once with its annotation.

    Attributes:
        sid: the id of the protein, also used in `f_<sid>`, `CYP3A4`.
        name: the name of the protein.
        uniprot: the UniProtKB accession of the human protein.
        ncit: the NCI Thesaurus code, if the thesaurus has a concept.
    """

    sid: str
    name: str
    uniprot: str
    ncit: str | None = None


def load_proteins() -> dict[str, Protein]:
    """Load the protein table `data/proteins.toml`.

    Returns:
        The proteins by their id.
    """
    table = load("proteins")["proteins"]
    return {
        sid: Protein(
            sid=sid,
            name=entry["name"],
            uniprot=entry["uniprot"],
            ncit=entry.get("ncit"),
        )
        for sid, entry in table.items()
    }


PROTEINS: dict[str, Protein] = load_proteins()
"""The proteins of the library by their id."""


@dataclass(frozen=True)
class Inhibition:
    """The inhibition of a protein by a substance, declared on the inhibitor.

    Attributes:
        protein: the id of the inhibited protein (key of `PROTEINS`).
        kind: the type of the inhibition.
        ki: the inhibition constant (of the unbound inhibitor).
        kiu: the second constant of a mixed inhibition (`ki` is the
            competitive one).
        kinact: the maximal inactivation rate of a mechanism-based inhibition
            (`ki` is its KI).
    """

    protein: str
    kind: Literal[
        "competitive", "noncompetitive", "uncompetitive", "mixed", "mechanism"
    ]
    ki: Q
    kiu: Q | None = None
    kinact: Q | None = None


@dataclass(frozen=True)
class Induction:
    """The induction of a protein by a substance, declared on the inducer.

    Attributes:
        protein: the id of the induced protein (key of `PROTEINS`).
        emax: the maximal increase of the expression (fold change - 1).
        ec50: the concentration of half-maximal induction (unbound).
    """

    protein: str
    emax: Q
    ec50: Q
